// Writes server/db/prod/fresh-start.sql: the minimum rows an EMPTY database needs so that admin can log in and see the
// full menu — company, division, financial year, one branch, admin user, the whole menu and the standard account groups.
// The menu rows are read from the project's own SQL files (server/db/dev/*.sql), not from a database.
//   node scripts/make-fresh-start.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const devDir = join(root, 'server/db/dev');
const { DEFAULT_GROUP } = await import(pathToFileURL(join(root, 'server/src/modules/books/sections.js')).href);

// "( 'a', 'b', null ), (...)" -> [['a','b',null], ...]  (quote-aware; stops at the end of the values list)
function tuples(text) {
  const rows = [];
  let i = 0;
  const ws = () => { while (/\s/.test(text[i])) i++; };
  for (;;) {
    ws();
    if (text[i] !== '(') break;
    i++;
    const row = [];
    for (;;) {
      ws();
      if (text[i] === "'") {
        let v = '';
        i++;
        for (;;) {
          if (text[i] === "'" && text[i + 1] === "'") { v += "'"; i += 2; } else if (text[i] === "'") { i++; break; } else v += text[i++];
        }
        row.push(v);
      } else {
        let v = '';
        while (text[i] !== ',' && text[i] !== ')') v += text[i++];
        v = v.trim();
        row.push(/^null$/i.test(v) ? null : v);
      }
      ws();
      if (text[i] === ',') { i++; continue; }
      if (text[i] === ')') { i++; break; }
      throw new Error(`bad values near: ${text.slice(i, i + 40)}`);
    }
    rows.push(row);
    ws();
    if (text[i] === ',') { i++; continue; }
    break;
  }
  return rows;
}

const tables = { MasterMenu: new Map(), SubMenu: new Map(), Sub_SubMenu: new Map() };
const colsOf = {};
const files = readdirSync(devDir).filter((f) => /\.sql$/i.test(f)).sort();
for (const f of files) {
  const src = readFileSync(join(devDir, f), 'utf8');
  const re = /insert\s+into\s+(MasterMenu|SubMenu|Sub_SubMenu)\s*\(([^)]*)\)\s*values\s*/gi;
  let m;
  while ((m = re.exec(src))) {
    const table = Object.keys(tables).find((t) => t.toLowerCase() === m[1].toLowerCase());
    const cols = m[2].split(',').map((c) => c.trim());
    colsOf[table] ??= cols;
    if (cols.join() !== colsOf[table].join()) throw new Error(`${f}: different column list for ${table}`);
    for (const r of tuples(src.slice(re.lastIndex))) {
      const key = table === 'MasterMenu' ? r[0] : table === 'SubMenu' ? `${r[0]}|${r[1]}` : r[0];
      if (!tables[table].has(key)) tables[table].set(key, r);
    }
  }
}

const lit = (v) => (v == null ? 'null' : `N'${String(v).replace(/'/g, "''")}'`);
const block = (table) => {
  const rows = [...tables[table].values()];
  return `-- ${table}: ${rows.length} rows\ninsert into ${table}(${colsOf[table].join(', ')}) values\n`
    + rows.map((r) => '  (' + r.map(lit).join(', ') + ')').join(',\n') + ';\n';
};

const groups = Object.entries(DEFAULT_GROUP).map(([section, name], n) => ({ code: `G${n + 1}`, name, section }));

const sql = `-- FRESH START — generated by scripts/make-fresh-start.mjs. Run on an EMPTY database (after deleting all data).
-- Then log in:  admin / admin123   Division: COURIER   Year: 2026-2027
-- (production mode asks for a new password right after the first login)
set nocount on;
set xact_abort on;
begin transaction;

-- company, division, financial year
insert into CompanyMster(CName, CCode, Division) values (N'RAMAS LOGISTICS PVT LTD', N'RELL', N'DIV1001');
insert into DivisionMaster(DivCode, DivName, Domain, CompanyCode, IsActive) values (N'DIV1001', N'COURIER', N'', N'1', 1);
insert into Financial_Year(Financial_Year, Status) values (N'2026-2027', N'true');

-- one state / zone / city and the head-office branch (admin logs in to HEAD OFFICE = B1001)
insert into state_master(state_code, state_name, StateCode, Gstin_No, active_flag) values (N'DL', N'DELHI', N'07', N'', N'Active');
insert into zone_master(zone_code, zone_name, zone_description, active_flag) values (N'NZ', N'NORTH ZONE', N'', N'Active');
insert into city_master(city_code, city_name, state_code, zone_code, oda, oda_km, active_flag) values (N'DEL', N'DELHI', N'DL', N'NZ', N'no', 0, N'Active');
insert into branch_master(branch_code, branch_name, city_code, state_code, zone_code, status, IsFranchisee, IsMasterFranchisee, company, ControllingBranch, short_code)
values (N'B1001', N'HEAD OFFICE', N'DEL', N'DL', N'NZ', N'Active', N'false', N'false', N'1', N'B1001', N'DEL');

-- admin login
insert into users(user_id, user_password, user_type, user_emp_type, user_branch, DivCode) values (N'admin', N'admin123', N'admin', N'Admin', N'', null);

-- the whole menu (admin sees every item)
${block('MasterMenu')}
${block('SubMenu')}
${block('Sub_SubMenu')}
-- standard account groups, each with its section (for Trial Balance / P&L / Balance Sheet)
insert into tblAccountGroup(GroupCode, GroupName) values
${groups.map((g) => `  (${lit(g.code)}, ${lit(g.name)})`).join(',\n')};
insert into tblAccountGroupInfo(GroupCode, Section, UpdatedBy) values
${groups.map((g) => `  (${lit(g.code)}, ${lit(g.section)}, N'setup')`).join(',\n')};

commit;
print 'Fresh start done - login: admin / admin123, Division COURIER, Year 2026-2027';
`;
mkdirSync(join(root, 'server/db/prod'), { recursive: true });
writeFileSync(join(root, 'server/db/prod/fresh-start.sql'), sql);
console.log(`server/db/prod/fresh-start.sql written: MasterMenu ${tables.MasterMenu.size}, SubMenu ${tables.SubMenu.size}, `
  + `Sub_SubMenu ${tables.Sub_SubMenu.size}, groups ${groups.length}`);
