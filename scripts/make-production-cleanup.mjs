// Writes server/db/prod/production-cleanup.sql: removes the demo data (rows tagged DMO…) and everything the automated
// tests leave behind, from a database that is going live. Built from the tests' own clean-up block (server/test/
// api.test.js before()) so the two never drift apart.
//   node scripts/make-production-cleanup.mjs
// Test dockets are recognised narrowly: "T" + up to 7 letters / digits (TP001, TAP002 …) — a real docket number is
// never matched. Everything runs in one transaction.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const testSrc = readFileSync(join(root, 'server/test/api.test.js'), 'utf8');
const start = testSrc.indexOf('// without recreating the dev database.');
const open = testSrc.indexOf('await query(`', start) + 'await query(`'.length;
const close = testSrc.indexOf('`);', open);
if (start < 0 || open < 20 || close < 0) throw new Error('Clean-up block not found in server/test/api.test.js');
let block = testSrc.slice(open, close).split('\n').map((l) => l.replace(/^\s{6}/, '')).join('\n').trim();
// "<column> like 'T%'" → only the recognised test dockets
block = block.replace(/([\w.]+) like 'T%'/g, '$1 in (select d from #td)');
if (/like 'T%'/.test(block)) throw new Error("an unconverted like 'T%' is left");

const demo = readFileSync(join(root, 'server/db/dev/demo/demo-remove.sql'), 'utf8')
  .split('\n').filter((l) => /^delete from /i.test(l.trim())).join('\n');

const sql = `-- PRODUCTION CLEAN-UP — generated by scripts/make-production-cleanup.mjs, do not edit by hand.
-- Removes (1) the demo data (all rows tagged DMO…) and (2) what the automated tests left behind (test dockets
-- "T" + up to 7 letters/digits, rows marked TST / ZTA / 777 / 999 / G-99000… / TS99…). Real entries are not touched.
-- One transaction: either everything is removed or nothing. Safe to run again.
set nocount on;
set xact_abort on;
begin transaction;

-- the test dockets (narrow: T + 1..7 letters / digits; real docket numbers never look like this)
if object_id('tempdb..#td') is not null drop table #td;
create table #td (d varchar(50) primary key);
insert into #td(d) select docket_no from grn_master
 where docket_no like 'T%' and len(docket_no) between 2 and 8 and docket_no not like '%[^A-Za-z0-9]%';
declare @testDockets int = (select count(*) from #td);
declare @demoDockets int = (select count(*) from grn_master where docket_no like 'DMO%');
print concat('Demo dockets: ', @demoDockets, ', test dockets: ', @testDockets);

-- (1) demo data
${demo}

-- (2) automated-test leftovers (same order as the tests' own clean-up)
${block}

-- accounts tests (ZTA …)
delete from tblAccountTrasaction where Mode = 'Payment Note' and VoucherNo in (select Payment_No from tbl_payment where Narration like 'ZTA%');
delete from tbl_payment_detail where Payment_No in (select Payment_No from tbl_payment where Narration like 'ZTA%');
delete from tbl_payment where Narration like 'ZTA%';
delete from tblAccountTrasaction where Mode = 'Contra Note' and VoucherNo in (select Contra_No from tbl_contra where Narration like 'ZTA%');
delete from tbl_contra where Narration like 'ZTA%';
delete from tblAccountTrasaction where VoucherNo like 'ZTA%' or LedgerCode in (select LedgerCode from tblAccountLedger where LedgerName like 'ZTA %');
delete from tblLedgerHierarchy where LedgerCode in (select LedgerCode from tblAccountLedger where LedgerName like 'ZTA %');
delete from tblAccountLedger where LedgerName like 'ZTA %';
delete from tblAccountGroupInfo where GroupCode in (select GroupCode from tblAccountGroup where GroupName like 'ZTA %');
delete from tblAccountGroup where GroupName like 'ZTA %';

-- pickups / manifests left empty after the dockets went
delete from Pick_up_entry where pickup_no not in (select Pickup_no from Pick_Up_grn);
delete from mainfest_entry where mainfest_no not in (select Manifest_no from Manifest_grn);

drop table #td;
commit;
print 'Production clean-up done';
`;
mkdirSync(join(root, 'server/db/prod'), { recursive: true });
writeFileSync(join(root, 'server/db/prod/production-cleanup.sql'), sql);
console.log(`server/db/prod/production-cleanup.sql written (${sql.split('\n').length} lines)`);
